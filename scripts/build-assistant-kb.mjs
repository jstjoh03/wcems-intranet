// Generates supabase/functions/ask-assistant/kb-content.ts from kb/*.md.
//
// The edge bundle can't reliably read static files at runtime
// (Deno.readTextFile on bundled assets 500'd in production, 2026-10-24),
// so the markdown is baked into a TS module and imported statically.
// The kb/*.md files stay the SOURCE OF TRUTH — edit those, run this,
// redeploy the function:
//
//   node scripts/build-assistant-kb.mjs
//   npx supabase functions deploy ask-assistant
//
// Article order comes from the KB_FILES manifest in index.ts so the
// prompt (and its cache) stays byte-stable.

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const fnDir = resolve(dirname(fileURLToPath(import.meta.url)), '../supabase/functions/ask-assistant')

const indexSrc = readFileSync(resolve(fnDir, 'index.ts'), 'utf8')
const manifestMatch = indexSrc.match(/const KB_FILES = \[([\s\S]*?)\]/)
if (!manifestMatch) {
  console.error('KB_FILES manifest not found in index.ts')
  process.exit(1)
}
const files = [...manifestMatch[1].matchAll(/'([^']+\.md)'/g)].map((m) => m[1])
if (!files.length) {
  console.error('KB_FILES manifest is empty')
  process.exit(1)
}

const entries = files.map((f) => {
  const raw = readFileSync(resolve(fnDir, 'kb', f), 'utf8').replace(/\r\n/g, '\n')
  if (!raw.startsWith('---\n')) {
    console.error(`kb/${f} is missing front-matter`)
    process.exit(1)
  }
  return `  { file: ${JSON.stringify(f)}, raw: ${JSON.stringify(raw)} },`
})

const out = `// GENERATED by scripts/build-assistant-kb.mjs — do not edit by hand.
// Source of truth: the markdown files under ./kb/. Edit those, re-run the
// script, redeploy. Order mirrors KB_FILES in index.ts (cache stability).

export const KB_RAW: ReadonlyArray<{ file: string; raw: string }> = [
${entries.join('\n')}
]
`
writeFileSync(resolve(fnDir, 'kb-content.ts'), out, 'utf8')
console.log(`kb-content.ts written — ${files.length} articles, ${out.length} bytes`)
